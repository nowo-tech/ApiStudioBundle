<?php

declare(strict_types=1);

namespace Nowo\ApiStudioBundle\DependencyInjection;

use Nowo\ApiStudioBundle\EventListener\LocaleSubscriber;
use Nowo\ApiStudioBundle\Security\ApiStudioAccessPolicy;
use Nowo\ApiStudioBundle\Security\ApiStudioHistoryScope;
use Nowo\ApiStudioBundle\Twig\ApiStudioExtension as ApiStudioTwigExtension;
use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

use function is_string;
use function preg_match;

/**
 * Configuration tree for nowo_api_studio.
 */
final class Configuration implements ConfigurationInterface
{
    public const ALIAS = 'nowo_api_studio';

    public const CSS_FRAMEWORKS = ['bootstrap5', 'tailwind', 'foundation', 'custom'];

    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder(self::ALIAS);
        $rootNode    = $treeBuilder->getRootNode();

        $rootNode
            ->children()
                ->booleanNode('enabled')
                    ->defaultTrue()
                ->end()
                ->arrayNode('environments')
                    ->info('Environments created for each workspace created from the UI (first = default). Empty list disables seeding.')
                    ->prototype('scalar')->end()
                    ->defaultValue(['dev', 'test', 'prod'])
                ->end()
                ->scalarNode('connection')
                    ->defaultValue('default')
                    ->cannotBeEmpty()
                ->end()
                ->scalarNode('entity_manager')
                    ->defaultNull()
                    ->info('Doctrine entity manager the Api Studio entities are mapped on (1.12), e.g. a dedicated "api_studio" manager of a DDD host. The entities are then mapped on that manager only (also with auto_mapping on the default one) and every read, write and reset of the bundle uses it. Null (default) = the manager that maps ApiWorkspace (the default one in a standard host).')
                    ->validate()
                        ->ifTrue(static fn (mixed $value): bool => $value !== null && (!is_string($value) || preg_match('/^[A-Za-z0-9_]+$/', $value) !== 1))
                        ->thenInvalid('The entity_manager must be the name of a Doctrine entity manager (letters, digits and underscores).')
                    ->end()
                ->end()
                ->scalarNode('table_prefix')
                    ->defaultValue('api_studio_')
                    ->cannotBeEmpty()
                    ->validate()
                        ->ifTrue(static fn (mixed $value): bool => !is_string($value) || !preg_match('/^[a-z0-9_]+$/', $value))
                        ->thenInvalid('The table_prefix must contain only lowercase letters, numbers, and underscores.')
                    ->end()
                ->end()
                ->arrayNode('ui')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('path')
                            ->defaultValue('/api-studio')
                            ->cannotBeEmpty()
                            ->info('Dashboard path prefix (host should lock with security.access_control).')
                        ->end()
                        ->arrayNode('path_requirements')
                            ->info('Requirements of the {placeholders} of ui.path (1.11), e.g. {organization: "[0-9a-f-]{36}"}; a placeholder without one matches [^/]+.')
                            ->useAttributeAsKey('name')
                            ->scalarPrototype()->end()
                            ->defaultValue([])
                        ->end()
                        ->scalarNode('layout_template')
                            ->defaultNull()
                            ->info('Layout the Api Studio pages (UiKit page scaffolds) extend. Null (default) = nowo_ui_kit.layouts.admin, set once for every UiKit bundle. A layout that renders the UiKit canonical blocks is used as is; a pre-1.10 layout that renders {% block body %} is wrapped in a deprecated bridge.')
                        ->end()
                        ->enumNode('css_framework')
                            ->values(self::CSS_FRAMEWORKS)
                            ->defaultNull()
                            ->info('Deprecated since 1.10: the CSS stack is nowo_ui_kit.css_framework (UiKit page contract). When set (and nowo_ui_kit.css_framework is not), it still seeds nowo_ui_kit.css_framework / icon_set and the FormKit css_framework.')
                        ->end()
                        ->enumNode('locale_scope')
                            ->values(LocaleSubscriber::SCOPES)
                            ->defaultValue(LocaleSubscriber::SCOPE_ROUTES)
                            ->info('Which requests get the Api Studio UI locale: routes (default since 1.11) = Api Studio pages only; global = every request of the host (1.10 behaviour); none = never (the host owns the locale).')
                        ->end()
                        ->scalarNode('default_locale')
                            ->defaultValue('en')
                            ->cannotBeEmpty()
                        ->end()
                        ->arrayNode('locales')
                            ->scalarPrototype()->end()
                            ->defaultValue(['en', 'es', 'fr', 'it'])
                            ->requiresAtLeastOneElement()
                        ->end()
                        ->integerNode('request_timeout_seconds')
                            ->defaultValue(30)
                            ->min(1)
                            ->max(300)
                        ->end()
                        ->integerNode('list_page_size')
                            ->info('Rows per page on the workspace list and the dashboard (REQ-PERF-001).')
                            ->defaultValue(50)
                            ->min(1)
                            ->max(500)
                        ->end()
                        ->arrayNode('required_roles')
                            ->info('Legacy role list used when security.access_roles is empty. An empty effective list denies; both empty fails compilation unless access_checker or allow_unauthenticated is set.')
                            ->scalarPrototype()->end()
                            ->defaultValue(['ROLE_ADMIN'])
                            ->example(['ROLE_ADMIN', 'ROLE_API_STUDIO'])
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('execution_url_allowlist')
                    ->info('Optional allowlist for outbound request URLs: exact host (api.example.com), host suffix (.example.com), URL with scheme/port/path prefix, or regex with # prefix. Empty = any public URL after SSRF check unless execution_url_allowlist_required is true.')
                    ->scalarPrototype()->end()
                    ->defaultValue([])
                    ->example(['api.example.com', '.example.org', '#^https://staging\\.example\\.com/#'])
                ->end()
                ->integerNode('execution_max_redirects')
                    ->defaultValue(0)
                    ->min(0)
                    ->info('Redirects followed when executing requests. 0 (default) returns 3xx responses as-is. Followed hops are blocked from private networks but are not re-checked against execution_url_allowlist.')
                ->end()
                ->integerNode('execution_max_response_bytes')
                    ->defaultValue(10_485_760)
                    ->min(1024)
                    ->info('Largest response body (bytes) read from a remote API, SOAP endpoint or WSDL document (default 10 MiB); a bigger transfer is stopped and reported as an error.')
                ->end()
                ->booleanNode('execution_url_allowlist_required')
                    ->defaultFalse()
                    ->info('When true, an empty execution_url_allowlist fails container compilation. Recommended true in production.')
                ->end()
                ->arrayNode('secrets')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('encrypt')
                            ->defaultTrue()
                            ->info('Encrypt environment variables marked secret at rest (sodium). Existing plaintext values remain readable and are re-encrypted on next save.')
                        ->end()
                        ->scalarNode('encryption_key')
                            ->defaultNull()
                            ->info('Optional key material for secret encryption. Defaults to kernel.secret when null.')
                        ->end()
                        ->scalarNode('source')
                            ->defaultNull()
                            ->info('1.13: service id implementing ApiStudioSecretSourceInterface. A secret variable whose value is {{secret:<source>/<id>}} is then resolved on the server at execute time (per user and workspace, decided by the host); the value never reaches the browser, the history, logs or exports. null (default) = references are plain values, as before.')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('tenancy')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')
                            ->defaultFalse()
                            ->info('Tenants (1.11): each workspace belongs to a tenant resolved per request; lists, counts, the sidebar and lookups are scoped to it, and the workspace slug is unique per tenant. Maps two columns on the workspace table (migration). Literal boolean.')
                        ->end()
                        ->scalarNode('resolver')
                            ->defaultNull()
                            ->info('Service id implementing ApiStudioTenantResolverInterface (required when enabled, unless tenancy.provider is set): the tenant of an Api Studio request; null result = 404.')
                        ->end()
                        ->scalarNode('provider')
                            ->defaultNull()
                            ->info('Service id implementing ApiStudioTenantProviderInterface (1.12): a request-free alternative to tenancy.resolver for hosts that already know the current tenant (DDD application context). Set one of resolver or provider.')
                        ->end()
                        ->booleanNode('sql_filter')
                            ->defaultTrue()
                            ->info('With tenancy: also narrow every bundle query of an Api Studio request with a Doctrine SQL filter (defence in depth; the explicit checks stay the control).')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('history')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->enumNode('scope')
                            ->values(ApiStudioHistoryScope::SCOPES)
                            ->defaultValue(ApiStudioHistoryScope::SCOPE_ENDPOINT)
                            ->info('endpoint (default) = one shared history per endpoint; user = rows record who executed them (maps executed_by, migration) and users see only their own unless granted history.view_all.')
                        ->end()
                        ->scalarNode('actor_resolver')
                            ->defaultNull()
                            ->info('Service id implementing ApiStudioActorResolverInterface (history.scope: user). Default: the user identifier (hashed beyond 64 characters).')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('folders')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')
                            ->defaultFalse()
                            ->info('Nested folders in each service (1.14): tree with drag & drop, auth and headers inherited from the folders, folder-aware Postman / OpenAPI import and OpenAPI export. Maps the folder table and the endpoint folder_id column (migration). false (default) = the 1.13 schema and pages.')
                        ->end()
                        ->integerNode('max_depth')
                            ->defaultValue(8)
                            ->min(1)
                            ->max(32)
                            ->info('Deepest folder level allowed (a top-level folder has depth 1). Checked on create, move and import.')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('scripts')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->enumNode('mode')
                            ->values(ApiStudioTwigExtension::SCRIPTS_MODES)
                            ->defaultValue(ApiStudioTwigExtension::SCRIPTS_INLINE)
                            ->info('Pre/post request scripts of the console. inline (default; deprecated since 1.15, sandbox becomes the default in 2.0) = run in the page, unsandboxed, with the session of whoever sends the request (needs script-src \'unsafe-eval\'); sandbox (1.15) = run in an opaque-origin iframe with its own CSP (no network, no access to the page or the session; the page needs frame-src \'self\' and no \'unsafe-eval\'); disabled = no script tab, no script code sent to the browser (stored scripts are kept).')
                        ->end()
                        ->arrayNode('limits')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->integerNode('time_ms')
                                    ->defaultValue(2000)
                                    ->min(100)
                                    ->max(30000)
                                    ->info('sandbox mode and server runner (1.15): wall time of one phase (pre or post) before the frame / process is torn down and the request fails.')
                                ->end()
                                ->integerNode('memory_mb')
                                    ->defaultValue(64)
                                    ->min(16)
                                    ->max(1024)
                                    ->info('Server runner (1.15): memory of the sidecar, handed to its command through the {memory_mb} placeholder (V8 heap limit by default).')
                                ->end()
                                ->integerNode('output_kb')
                                    ->defaultValue(256)
                                    ->min(16)
                                    ->max(10240)
                                    ->info('Server runner (1.15): most stdout + stderr of one run; the sidecar is killed past it.')
                                ->end()
                                ->integerNode('send_requests')
                                    ->defaultValue(10)
                                    ->min(0)
                                    ->max(100)
                                    ->info('sandbox mode and server runner (1.15): pm.sendRequest calls allowed per phase.')
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('server_runner')
                            ->addDefaultsIfNotSet()
                            ->info('Server-side script runner (1.15) for unattended runs (collection runner, CLI, monitors): one sidecar process per run (needs proc_open). Disabled = unattended runs report scripts as not run.')
                            ->children()
                                ->booleanNode('enabled')->defaultFalse()->end()
                                ->arrayNode('command')
                                    ->scalarPrototype()->end()
                                    ->defaultValue(['deno', 'run', '--quiet', '--no-prompt', '--no-config', '--no-lock', '--no-npm', '--no-remote', '--v8-flags=--max-old-space-size={memory_mb}', '{runner}'])
                                    ->info('Sidecar command: {runner} = the bundled runner script, {memory_mb} = scripts.limits.memory_mb. The default Deno command grants no permission (no file system, network, environment or subprocess). Node 25+ works too (node --permission --max-old-space-size={memory_mb} {runner}); the runner refuses Node below 25 or without --permission (no network block: SSRF).')
                                ->end()
                            ->end()
                        ->end()
                        ->booleanNode('confirm_stored')
                            ->defaultTrue()
                            ->info('inline mode (1.13.2): before Send runs a stored service / endpoint script this browser session has not approved yet, the console shows its code and asks to run it or to send without scripts (approval kept per SHA-256 of the code in sessionStorage). Code typed in the console by the user is not asked. false = 1.13.1 behaviour (stored scripts run without asking).')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('security')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('access_checker')
                            ->defaultNull()
                        ->end()
                        ->scalarNode('permission_checker')
                            ->defaultNull()
                            ->info('Service id implementing ApiStudioPermissionCheckerInterface (1.11): per-workspace, per-action decisions; forbidden actions are hidden, not viewable workspaces answer 404. Null = everything granted to whoever passes the role / access checks (1.10 behaviour).')
                        ->end()
                        ->scalarNode('folder_permission_checker')
                            ->defaultNull()
                            ->info('Service id implementing ApiStudioFolderPermissionCheckerInterface (1.14, folders.enabled): folder-level sharing on top of the workspace decisions; it can only deny (hidden folders answer 404, read-only folders 403). Null = folders follow their workspace.')
                        ->end()
                        ->arrayNode('access_roles')
                            ->scalarPrototype()->end()
                            ->defaultValue(['ROLE_ADMIN'])
                            ->info('Required roles for Api Studio UI (user needs at least one). Empty falls back to ui.required_roles; an empty effective list denies, and compilation fails unless access_checker or allow_unauthenticated is set.')
                        ->end()
                        ->booleanNode('allow_unauthenticated')
                            ->defaultFalse()
                            ->info('DEV/DEMO ONLY. When true, the UI may load without SecurityBundle / without login. Production MUST keep false.')
                        ->end()
                        ->scalarNode('feature_gate')
                            ->defaultNull()
                            ->info('Service id implementing ApiStudioFeatureGateInterface (1.16): whether Api Studio is available for the tenant and user (e.g. a plan feature). Consulted on every Api Studio route after studio.open, before the controller; false answers access_denied_response. Null = no gate.')
                        ->end()
                        ->enumNode('access_denied_response')
                            ->values(ApiStudioAccessPolicy::RESPONSES)
                            ->defaultValue(ApiStudioAccessPolicy::FORBIDDEN)
                            ->info('1.16: 403 (default) = refused actions answer 403; 404 = every refusal on an Api Studio route (permission checker, tenancy, feature gate, role / access checks of a signed-in user) answers the same 404 as a genuine not-found (no oracle). Literal value.')
                        ->end()
                        ->arrayNode('host_routes')
                            ->info('1.16: host routes guarded like the bundle\'s own (enabled check, tenant, roles, access checker, studio.open, feature_gate, the 403 / 404 policy, no-store): route name => studio.open | workspace.create. Workspace actions stay in the host controller (ApiStudioAuthorization::requireWorkspace()).')
                            ->useAttributeAsKey('route')
                            ->scalarPrototype()->end()
                            ->defaultValue([])
                            ->example(['app_api_studio_share' => 'studio.open'])
                        ->end()
                    ->end()
                ->end()
            ->end();

        return $treeBuilder;
    }
}
