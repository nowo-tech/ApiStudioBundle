/**
 * 1.11 host hooks end to end: tenants from the URL placeholder, per-tenant slugs, scoped lists and lookups, the
 * permission checker (hidden actions, 404 / 403), the created event inside the transaction, per-user history and
 * scripts disabled.
 */
final class TenancyAndPermissionsTest extends WebTestCase
{
    private KernelBrowser $client;

    /** @var array{acme: int, beta: int, service: int, endpoint: int, environment: int} */
    private array $ids;

    protected static function getKernelClass(): string
    {
        return TenancyTestKernel::class;
    }

    protected function setUp(): void
    {
        $this->client = self::createClient();
        $this->client->catchExceptions(false);
        // One container for the whole test: the checker / listener doubles keep their state between requests.
        $this->client->disableReboot();

        $em       = $this->em();
        $metadata = $em->getMetadataFactory()->getAllMetadata();
        $tool     = new SchemaTool($em);
        $tool->dropSchema($metadata);
        $tool->createSchema($metadata);

        $acme    = (new ApiWorkspace('Acme payments', 'payments'))->assignTenant(new ApiStudioTenant('org', 'acme'));
        $beta    = (new ApiWorkspace('Beta payments', 'payments'))->assignTenant(new ApiStudioTenant('org', 'beta'));
        $service = (new ApiService('Orders', 'orders'))->setBaseUrl('https://93.184.215.14')->setPreRequestScript('pm.environment.set("a", "1")');
        $acme->addService($service);
        $endpoint    = (new ApiEndpoint('List', 'list'))->setPath('/orders')->setService($service);
        $environment = new ApiEnvironment('Dev', 'dev');
        $acme->addEnvironment($environment);
        foreach ([$acme, $beta, $service, $endpoint, $environment] as $entity) {
            $em->persist($entity);
        }
        $em->flush();
        $em->clear();

        $this->ids = [
            'acme'        => (int) $acme->getId(),
            'beta'        => (int) $beta->getId(),
            'service'     => (int) $service->getId(),
            'endpoint'    => (int) $endpoint->getId(),
            'environment' => (int) $environment->getId(),
        ];
    }

    public function testListsCountsAndSidebarOnlyShowTheTenantsWorkspaces(): void
    {
        $this->client->request('GET', '/orgs/acme/api-studio/');
        self::assertResponseIsSuccessful();
        $html = (string) $this->client->getResponse()->getContent();
        self::assertStringContainsString('Acme payments', $html);
        self::assertStringNotContainsString('Beta payments', $html);
        // Links generated by the bundle carry the current {org}.
        self::assertStringContainsString(sprintf('/orgs/acme/api-studio/workspaces/%d', $this->ids['acme']), $html);

        $this->client->request('GET', '/orgs/beta/api-studio/workspaces');
        $html = (string) $this->client->getResponse()->getContent();
        self::assertStringContainsString('Beta payments', $html);
        self::assertStringNotContainsString('Acme payments', $html);

        // A tenant with no workspace sees none.
        $this->client->request('GET', '/orgs/gamma/api-studio/workspaces');
        self::assertStringNotContainsString('payments', (string) $this->client->getResponse()->getContent());
    }

