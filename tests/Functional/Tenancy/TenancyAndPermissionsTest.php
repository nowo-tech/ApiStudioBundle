    }

    #[DataProvider('acmeUrls')]
    public function testAnotherTenantsWorkspaceIsNotFound(string $pattern): void
    {
        $path = sprintf($pattern, $this->ids['acme'], $this->ids['service'], $this->ids['endpoint'], $this->ids['environment']);

        $this->client->request('GET', '/orgs/acme/api-studio' . $path);
        self::assertResponseIsSuccessful();

        $this->expectException(NotFoundHttpException::class);
        $this->client->request('GET', '/orgs/beta/api-studio' . $path);
    }

    public function testRequestsWithoutATenantOrWithABadPlaceholderAreNotFound(): void
    {
        try {
            $this->client->request('GET', '/orgs/nobody/api-studio/');
            self::fail('No tenant: 404.');
        } catch (NotFoundHttpException) {
        }

        $this->expectException(NotFoundHttpException::class);
        $this->client->request('GET', '/orgs/ACME/api-studio/');
    }

    public function testSlugsAreUniquePerTenant(): void
    {
        $crawler = $this->client->request('GET', '/orgs/gamma/api-studio/workspaces/new');
        $this->client->submit($crawler->filter('form[name="api_workspace_form"]')->form([
            'api_workspace_form[name]' => 'Gamma payments',
            'api_workspace_form[slug]' => 'payments',
        ]));
        self::assertResponseRedirects();

        $created = $this->em()->getRepository(ApiWorkspace::class)->findOneBy(['name' => 'Gamma payments']);
        self::assertInstanceOf(ApiWorkspace::class, $created);
        self::assertTrue($created->getTenant()->equals(new ApiStudioTenant('org', 'gamma')));
        self::assertCount(1, $this->listener()->created);
        self::assertSame('org:gamma', $this->listener()->created[0]->tenant->key());

        $crawler = $this->client->request('GET', '/orgs/gamma/api-studio/workspaces/new');
        $this->client->submit($crawler->filter('form[name="api_workspace_form"]')->form([
            'api_workspace_form[name]' => 'Gamma again',
            'api_workspace_form[slug]' => 'payments',
        ]));
        self::assertResponseStatusCodeSame(422);
    }

    public function testAFailingCreatedListenerRollsTheWorkspaceBack(): void
    {
        $crawler = $this->client->request('GET', '/orgs/acme/api-studio/workspaces/new');
        $form    = $crawler->filter('form[name="api_workspace_form"]')->form([
            'api_workspace_form[name]' => 'Boom',
            'api_workspace_form[slug]' => 'boom',
        ]);

        try {
            $this->client->submit($form);
            self::fail('The listener exception propagates.');
        } catch (RuntimeException $e) {
            self::assertSame('Host listener failed.', $e->getMessage());
        }

        self::assertSame(0, $this->freshEm()->getRepository(ApiWorkspace::class)->count(['slug' => 'boom']));
    }

    public function testForbiddenActionsAreHiddenAndRefused(): void
    {
        $this->checker()->denied = [ApiStudioAction::WorkspaceEdit, ApiStudioAction::WorkspaceManage, ApiStudioAction::WorkspaceImport, ApiStudioAction::WorkspaceExportVariables, ApiStudioAction::WorkspaceRun, ApiStudioAction::WorkspaceCreate];
        $base                    = sprintf('/orgs/acme/api-studio/workspaces/%d', $this->ids['acme']);

        $this->client->request('GET', $base);
        self::assertResponseIsSuccessful();
        $html = (string) $this->client->getResponse()->getContent();
        self::assertStringNotContainsString($base . '/services/new', $html);
        self::assertStringNotContainsString($base . '/edit', $html);
        self::assertStringNotContainsString('/export/variables.', $html);
        self::assertStringNotContainsString('/import/openapi', $html);
        self::assertStringNotContainsString('/orgs/acme/api-studio/workspaces/new', $html);

        $this->client->request('GET', sprintf('%s/services/%d/endpoints/%d', $base, $this->ids['service'], $this->ids['endpoint']));
        $html = (string) $this->client->getResponse()->getContent();
        self::assertStringNotContainsString('id="tester-send"', $html);
        self::assertStringNotContainsString('id="tester-save-request"', $html);
        // scripts.mode: disabled: no script tab, no script code in the page, a notice instead.
        self::assertStringNotContainsString('data-subtab="pre"', $html);
        self::assertStringNotContainsString('pm.environment.set', $html);
        self::assertStringContainsString('api-studio-scripts-disabled', $html);

        foreach (['/services/new', '/edit', '/import/openapi'] as $suffix) {
            try {
                $this->client->request('GET', $base . $suffix);
                self::fail($suffix . ' must be refused.');
            } catch (AccessDeniedHttpException $e) {
                self::assertStringContainsString('not allowed', $e->getMessage());
            }
        }

        try {
            $this->client->request('GET', '/orgs/acme/api-studio/workspaces/new');
            self::fail('workspace.create denied: 403.');
        } catch (AccessDeniedHttpException) {
        }

        $this->client->request('POST', sprintf('/orgs/acme/api-studio/execute/%d', $this->ids['endpoint']), [], [], ['HTTP_X_CSRF_TOKEN' => 'any', 'CONTENT_TYPE' => 'application/json'], '{}');
        // CSRF first (403 JSON), then the run permission (403 JSON): never sent either way.
        self::assertResponseStatusCodeSame(403);
    }

    public function testRunIsRefusedAsJsonAndOtherTenantsEndpointsAreNotFound(): void
    {
        $page                    = $this->client->request('GET', sprintf('/orgs/acme/api-studio/workspaces/%d/services/%d/endpoints/%d', $this->ids['acme'], $this->ids['service'], $this->ids['endpoint']));
        $token                   = (string) $page->filter('#api-studio-tester')->attr('data-csrf-token');
        $this->checker()->denied = [ApiStudioAction::WorkspaceRun];

        $this->client->request('POST', sprintf('/orgs/acme/api-studio/execute/%d', $this->ids['endpoint']), [], [], ['HTTP_X_CSRF_TOKEN' => $token, 'CONTENT_TYPE' => 'application/json'], '{}');
        self::assertResponseStatusCodeSame(403);
        self::assertSame('{"error":"forbidden"}', $this->client->getResponse()->getContent());

        $this->client->request('POST', sprintf('/orgs/beta/api-studio/execute/%d', $this->ids['endpoint']), [], [], ['HTTP_X_CSRF_TOKEN' => $token, 'CONTENT_TYPE' => 'application/json'], '{}');
        self::assertResponseStatusCodeSame(404);
        self::assertSame(0, $this->em()->getRepository(ApiRequestHistory::class)->count([]));
    }

    public function testNotViewableWorkspacesDisappearAndStudioOpenGatesEverything(): void
